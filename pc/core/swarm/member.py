"""Описание участника команды: имя, зона ответственности и набор инструментов.

Ключевая идея эксперимента — РАЗДЕЛЕНИЕ ВОЗМОЖНОСТЕЙ. У каждого участника свой
урезанный набор инструментов, дополняющий других. Никто не может закрыть задачу
в одиночку — например, кодер умеет писать код, но не умеет запускать тесты, а
тестировщик умеет запускать тесты, но не умеет править код. Поэтому им приходится
координироваться через общий чат.

Ограничение через набор инструментов надёжнее ограничения в промпте: чего нет в
схеме — того модель не вызовет (см. docs/ARCHITECTURE.md, §6).
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path


@dataclass(slots=True)
class MemberSpec:
    """Один агент-участник группового чата."""

    #: Короткое уникальное имя-позывной (им подписаны сообщения в чате).
    name: str
    #: Роль в одну строку («аналитик», «кодер», «тестировщик»).
    role: str
    #: Устав: за что отвечает, что делать МОЖНО, а что — НЕ его зона.
    charter: str
    #: Имена встроенных инструментов, доступных участнику (кроме инструментов чата,
    #: они добавляются всем автоматически). Пустой список = только чат.
    tools: list[str] = field(default_factory=list)


def build_default_team() -> list[MemberSpec]:
    """Демо-команда из трёх программистов с взаимодополняющими правами.

    Ни один не может сдать задачу сам:
      * аналитик проектирует, но не пишет и не запускает код;
      * кодер пишет код, но не может его проверить (нет тестов/линтера/запуска);
      * тестировщик запускает и проверяет, но не может править код.
    Рабочий цикл рождается только через чат: план → реализация → проверка → правки.
    """
    read_tools = ["read_file", "list_dir", "find_files", "grep_search", "code_map", "find_symbol"]
    return [
        MemberSpec(
            name="Аналитик",
            role="аналитик-проектировщик",
            charter=(
                "Ты декомпозируешь задачу и проектируешь решение. МОЖНО: изучать проект, "
                "написать план/спецификацию в отдельный файл (например PLAN.md), описать "
                "интерфейсы и распределить работу между коллегами через чат. НЕЛЬЗЯ писать "
                "код решения и что-либо запускать — это зоны кодера и тестировщика. Твой "
                "результат — понятный план в чате, по которому команда сможет работать."
            ),
            tools=[*read_tools, "write_file", "update_plan"],
        ),
        MemberSpec(
            name="Кодер",
            role="разработчик",
            charter=(
                "Ты пишешь код решения по плану аналитика. МОЖНО: создавать и править файлы "
                "кода (write_file, edit_file, apply_patch). НЕЛЬЗЯ запускать тесты, линтер и "
                "код — у тебя нет таких инструментов, поэтому убедиться в работоспособности "
                "сам ты не можешь. Закончив кусок, ОБЯЗАТЕЛЬНО попроси тестировщика в чате "
                "проверить, и чини по его отчётам."
            ),
            tools=[*read_tools, "write_file", "edit_file", "apply_patch"],
        ),
        MemberSpec(
            name="Тестировщик",
            role="тестировщик-контролёр",
            charter=(
                "Ты проверяешь то, что написал кодер. МОЖНО: запускать тесты и линтер "
                "(run_tests, run_lint), выполнять код (run_python), читать файлы. НЕЛЬЗЯ "
                "править код — если нашёл проблему, опиши её в чате и попроси кодера "
                "исправить. Задача считается закрытой, только когда проверки зелёные — "
                "об этом сообщи в чат."
            ),
            tools=[*read_tools, "run_tests", "run_lint", "run_python"],
        ),
    ]


def load_team(path: str | Path) -> list[MemberSpec]:
    """Читает команду из JSON-файла: список объектов {name, role, charter, tools}.

    Формат намеренно простой, чтобы эксперимент можно было настроить без правки кода.
    """
    raw = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(raw, list):
        raise ValueError("Файл команды должен содержать JSON-список участников.")
    members: list[MemberSpec] = []
    for i, item in enumerate(raw):
        if not isinstance(item, dict):
            raise ValueError(f"Участник #{i + 1} должен быть объектом JSON.")
        try:
            members.append(
                MemberSpec(
                    name=str(item["name"]).strip(),
                    role=str(item.get("role", "участник")).strip(),
                    charter=str(item["charter"]).strip(),
                    tools=[str(t) for t in item.get("tools", [])],
                )
            )
        except KeyError as exc:
            raise ValueError(f"Участник #{i + 1}: отсутствует обязательное поле {exc}.") from exc
    return members
