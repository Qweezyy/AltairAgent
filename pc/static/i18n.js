  function readLang() {
    try {
      var v = localStorage.getItem(LS_KEY);
      if (v === "en" || v === "ru") return v;
    } catch (e) {}
    return DEFAULT;
  }
  var _lang = readLang();

  function t(key, vars) {
    var table = DICT[_lang] || DICT.en;
    var s = table[key];
    if (s == null) s = DICT.en[key];
    if (s == null) return key;
    if (vars) s = s.replace(/\{(\w+)\}/g, function (_, k) { return vars[k] != null ? vars[k] : "{" + k + "}"; });
    return s;
  }

  function apply(root) {
    root = root || document;
    root.querySelectorAll("[data-i18n]").forEach(function (el) { el.textContent = t(el.getAttribute("data-i18n")); });
    root.querySelectorAll("[data-i18n-html]").forEach(function (el) { el.innerHTML = t(el.getAttribute("data-i18n-html")); });
    root.querySelectorAll("[data-i18n-ph]").forEach(function (el) { el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph"))); });
    root.querySelectorAll("[data-i18n-tip]").forEach(function (el) { el.setAttribute("data-tip", t(el.getAttribute("data-i18n-tip"))); });
  }

  function setLang(l) {
    if (l !== "en" && l !== "ru") return;
    _lang = l;
    try { localStorage.setItem(LS_KEY, l); } catch (e) {}
    try { document.documentElement.lang = l; } catch (e) {}
    apply(document);
    try { window.dispatchEvent(new CustomEvent("i18n:changed", { detail: { lang: l } })); } catch (e) {}
  }

  window.I18N = { t: t, lang: function () { return _lang; }, setLang: setLang, apply: apply, DICT: DICT };
